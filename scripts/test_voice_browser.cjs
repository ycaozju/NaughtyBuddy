#!/usr/bin/env node
/* Real browser voice-settings acceptance. Clone upload is synthetic MeloTTS;
 * recording cancellation uses Chrome's silent fake microphone, never hardware.
 * Normal browser autoplay policy is retained. */
const { chromium } = require('/home/timocy/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const base = process.env.BABYBOT_URL || 'http://127.0.0.1:8765';
const outputArg = process.argv.indexOf('--output');
const output = path.resolve(root, outputArg < 0 ? 'reports/voice-browser.json' : process.argv[outputArg + 1]);
const credentials = JSON.parse(fs.readFileSync(path.join(root, '.runtime/credentials.json')));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'reports/voice-fixtures.json')));
const reference = manifest.fixtures.find(f => f.name === 'reference');
assert.ok(reference && reference.duration_s >= 3 && reference.duration_s <= 20);
assert.equal(createHash('sha256').update(fs.readFileSync(reference.path)).digest('hex'), reference.sha256);
const silencePath = path.join(root, '.runtime/voice-fixtures/silence.wav');
const silence = Buffer.alloc(44 + 32000);
silence.write('RIFF'); silence.writeUInt32LE(silence.length - 8, 4); silence.write('WAVEfmt ', 8);
silence.writeUInt32LE(16, 16); silence.writeUInt16LE(1, 20); silence.writeUInt16LE(1, 22);
silence.writeUInt32LE(16000, 24); silence.writeUInt32LE(32000, 28); silence.writeUInt16LE(2, 32);
silence.writeUInt16LE(16, 34); silence.write('data', 36); silence.writeUInt32LE(32000, 40);
fs.writeFileSync(silencePath, silence);
const report = { timestamp: new Date().toISOString(), kind: 'real-voice-settings-browser', base,
  browser: 'Chrome headless with normal autoplay policy and preauthorized silent fake microphone',
  reference: { ...reference, synthetic_speech_only: true }, tests: [], api_events: [], page_errors: [], console_errors: [],
  limitations: ['Real physical microphone, speaker and Android behavior were not tested.',
    'Reference voice is generated by local MeloTTS; no user-owned voice was supplied or evaluated.',
    'Functional playback and ASR checks do not establish speaker resemblance or cloning quality.'] };
async function check(name, action) {
  const began = Date.now();
  try {
    const details = await action();
    report.tests.push({ name, passed: true, elapsed_ms: Date.now() - began, ...details });
    console.log(JSON.stringify({ test: name, passed: true }));
  } catch (error) {
    report.tests.push({ name, passed: false, elapsed_ms: Date.now() - began, error: error.message });
    throw error;
  }
}
(async () => {
  let browser, page, createdVoiceId, originalVoiceId;
  try {
    browser = await chromium.launch({ executablePath: '/opt/google/chrome/chrome', headless: true,
      args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream',
        `--use-file-for-fake-audio-capture=${silencePath}`] });
    const context = await browser.newContext({ viewport: { width: 1365, height: 1000 }, permissions: ['microphone'], locale: 'zh-CN' });
    page = await context.newPage();
    page.on('pageerror', e => report.page_errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') report.console_errors.push(m.text()); });
    page.on('response', response => {
      const url = new URL(response.url());
      if (url.pathname.startsWith('/api/voices')) report.api_events.push({ path: url.pathname,
        method: response.request().method(), status: response.status(), voice_id: response.headers()['x-voice-id'] || null });
    });
    page.on('dialog', dialog => dialog.accept()); // Only deletion of this test's synthetic custom voice.
    await page.addInitScript(() => {
      const qa = window.__voiceQA = { streams: [], stops: [], audio: [], csp: [] };
      const capture = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
      navigator.mediaDevices.getUserMedia = async (...args) => {
        const stream = await capture(...args);
        qa.streams.push(stream);
        for (const track of stream.getTracks()) {
          const stop = track.stop.bind(track);
          track.stop = () => { stop(); qa.stops.push({ state: track.readyState, time: performance.now() }); };
        }
        return stream;
      };
      const start = AudioBufferSourceNode.prototype.start;
      const stop = AudioBufferSourceNode.prototype.stop;
      AudioBufferSourceNode.prototype.start = function (...args) {
        const row = { mechanism: 'WebAudio', start: performance.now(), duration_s: this.buffer?.duration };
        this.__voiceQARow = row;
        qa.audio.push(row);
        this.addEventListener('ended', () => { row.ended = performance.now(); });
        return start.apply(this, args);
      };
      AudioBufferSourceNode.prototype.stop = function (...args) {
        if (this.__voiceQARow) this.__voiceQARow.stopped = performance.now();
        return stop.apply(this, args);
      };
      const play = HTMLMediaElement.prototype.play;
      const pause = HTMLMediaElement.prototype.pause;
      HTMLMediaElement.prototype.play = function (...args) {
        const row = { mechanism: 'HTMLMediaElement', requested_at: performance.now() };
        this.__voiceQARow = row;
        qa.audio.push(row);
        this.addEventListener('playing', () => { row.start = performance.now(); });
        this.addEventListener('ended', () => { row.ended = performance.now(); });
        return play.apply(this, args);
      };
      HTMLMediaElement.prototype.pause = function (...args) {
        if (this.__voiceQARow) this.__voiceQARow.stopped = performance.now();
        return pause.apply(this, args);
      };
      document.addEventListener('securitypolicyviolation', event => qa.csp.push({ directive: event.violatedDirective, blocked: event.blockedURI }));
    });
    const api = async () => page.evaluate(() => fetch('/api/voices').then(async r => ({ status: r.status, value: await r.json() })));
    const responseFor = (pathname, method = 'POST') => page.waitForResponse(response => new URL(response.url()).pathname === pathname && response.request().method() === method, { timeout: 180000 });
    const allTracksEnded = () => page.evaluate(() => window.__voiceQA.streams.every(s => s.getTracks().every(t => t.readyState === 'ended')));
    const unlock = async () => {
      await page.locator('#parent-open').click();
      await page.locator('#parent-pin').fill(process.env.BABYBOT_PARENT_PIN || credentials.parent_pin);
      await page.locator('#parent-unlock-form button').click();
      await page.locator('#voice-settings-panel').waitFor({ state: 'visible' });
      await page.waitForFunction(() => !document.querySelector('#voice-select').disabled, null, { timeout: 30000 });
    };
    await page.goto(base, { waitUntil: 'networkidle' });
    await check('Voice settings stay hidden until the adult unlocks them', async () => {
      assert.equal(await page.locator('#voice-settings-panel').isVisible(), false);
      await page.locator('#parent-open').click();
      assert.equal(await page.locator('#voice-settings-panel').isVisible(), false);
      await page.locator('#family-code').fill(process.env.BABYBOT_FAMILY_CODE || credentials.family_code);
      await page.locator('#login-form button').click();
      await page.locator('#parent-dialog').waitFor({ state: 'hidden' });
      await page.locator('#parent-open').click();
      assert.equal(await page.locator('#voice-settings-panel').isVisible(), false);
      await page.locator('#parent-close').click();
      await unlock();
      const catalog = await api();
      assert.equal(catalog.status, 200);
      assert.equal(catalog.value.clone_available, true);
      originalVoiceId = catalog.value.selected_id;
      report.initial_catalog = catalog.value;
      return { parent_only_ui: true, original_voice_id: originalVoiceId };
    });
    if (process.argv.includes('--screenshots-only')) {
      report.kind = 'voice-settings-visual-capture-no-model-inference';
      await check('Capture recording and locally decoded upload states without creating or synthesizing any voice', async () => {
        await page.locator('#voice-clone-details summary').click();
        await page.locator('#voice-consent').check();
        await page.locator('#voice-record-start').click();
        await page.waitForFunction(() => window.__voiceQA.streams.some(s => s.getTracks().some(t => t.readyState === 'live')));
        for (const name of ['voice-recording.png', 'voice-upload-ready.png']) {
          const previous = path.join(root, 'reports', name);
          if (fs.existsSync(previous)) {
            fs.mkdirSync(path.join(root, 'reports/history'), { recursive: true });
            fs.copyFileSync(previous, path.join(root, 'reports/history', `${name.replace('.png', '')}-${Date.now()}.png`));
          }
        }
        await page.locator('.voice-recorder').screenshot({ path: path.join(root, 'reports/voice-recording.png') });
        await page.locator('#voice-record-cancel').click();
        assert.equal(await allTracksEnded(), true);
        await page.locator('#voice-name').fill('浏览器合成参考验收');
        await page.locator('#voice-reference-text').fill(reference.text);
        await page.locator('#voice-file').setInputFiles(reference.path);
        await page.waitForFunction(() => !document.querySelector('#voice-create').disabled);
        await page.setViewportSize({ width: 1365, height: 1800 });
        await page.locator('#voice-clone-form').scrollIntoViewIfNeeded();
        await page.locator('#voice-clone-form').screenshot({ path: path.join(root, 'reports/voice-upload-ready.png') });
        await page.locator('#voice-sample-clear').click();
        await page.locator('#parent-close').click();
        assert.equal(await allTracksEnded(), true);
        assert.equal(report.api_events.some(e => e.method !== 'GET'), false, 'Screenshot-only mode must not mutate or invoke synthesis');
        return { model_requests: 0, voice_mutations: 0, synthetic_speech_only: true, all_tracks_ended: true };
      });
      assert.deepEqual(report.page_errors, []);
      assert.deepEqual(report.console_errors, []);
      report.passed = true;
      return;
    }
    const preset = report.initial_catalog.voices.find(v => v.available && v.id !== originalVoiceId && (v.name.includes('男') || v.gender === 'male')) ||
      report.initial_catalog.voices.find(v => v.available && v.id !== originalVoiceId && (v.name.includes('女') || v.gender === 'female'));
    assert.ok(preset, 'A different available preset is required to verify the save operation');
    await check('Adult selects a different preset, listens to real local audio and saves it', async () => {
      await page.locator('#voice-select').selectOption(preset.id);
      const before = await page.evaluate(() => window.__voiceQA.audio.length);
      const previewResponse = responseFor('/api/voices/preview');
      await page.locator('#voice-preview').click();
      const response = await previewResponse;
      assert.equal(response.status(), 200);
      assert.equal(response.headers()['x-voice-id'], preset.id);
      await page.waitForFunction(n => window.__voiceQA.audio.slice(n).some(a => a.start), before, { timeout: 30000 });
      await page.waitForFunction(n => window.__voiceQA.audio.slice(n).some(a => a.ended && !a.stopped), before, { timeout: 30000 });
      const saveResponse = responseFor('/api/voices/select');
      await page.locator('#voice-save').click();
      assert.equal((await saveResponse).status(), 200);
      assert.equal((await api()).value.selected_id, preset.id);
      await page.locator('#voice-settings-panel').screenshot({ path: path.join(root, 'reports/voice-settings-desktop.png') });
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.locator('#voice-settings-panel').scrollIntoViewIfNeeded();
      await page.screenshot({ path: path.join(root, 'reports/voice-settings-mobile.png') });
      await page.setViewportSize({ width: 1365, height: 1000 });
      return { selected_voice_id: preset.id, native_audio_playback_completed: true };
    });
    await check('Reference recording requires consent, and cancellation ends all fake microphone tracks without uploading', async () => {
      await page.locator('#voice-clone-details summary').click();
      assert.equal(await page.locator('#voice-record-start').isDisabled(), true);
      assert.equal(await page.locator('#voice-file').isDisabled(), true);
      await page.locator('#voice-consent').check();
      const uploadsBefore = report.api_events.filter(e => e.path === '/api/voices' && e.method === 'POST').length;
      await page.locator('#voice-record-start').click();
      await page.waitForFunction(() => window.__voiceQA.streams.some(s => s.getTracks().some(t => t.readyState === 'live')));
      await page.waitForTimeout(400);
      await page.locator('.voice-recorder').screenshot({ path: path.join(root, 'reports/voice-recording.png') });
      await page.locator('#voice-record-cancel').click();
      assert.equal(await allTracksEnded(), true);
      assert.equal(await page.locator('#voice-create').isDisabled(), true);
      assert.equal(report.api_events.filter(e => e.path === '/api/voices' && e.method === 'POST').length, uploadsBefore);
      return { physical_microphone: false, native_getUserMedia: true, no_upload_on_cancel: true };
    });
    await check('Closing adult settings during recording ends tracks, discards the sample and relocks controls', async () => {
      await page.locator('#voice-record-start').click();
      await page.waitForFunction(() => window.__voiceQA.streams.some(s => s.getTracks().some(t => t.readyState === 'live')));
      await page.locator('#parent-close').click();
      await page.locator('#parent-dialog').waitFor({ state: 'hidden' });
      assert.equal(await allTracksEnded(), true);
      assert.equal(await page.locator('#voice-settings-panel').isVisible(), false);
      await unlock();
      if (!await page.locator('#voice-clone-details').evaluate(element => element.open)) await page.locator('#voice-clone-details summary').click();
      assert.equal(await page.locator('#voice-create').isDisabled(), true);
      return { all_tracks_ended: true, unsaved_sample_discarded: true };
    });
    await check('Synthetic WAV upload creates a custom voice, displays feedback and produces a real preview', async () => {
      const before = (await api()).value;
      await page.locator('#voice-name').fill('浏览器合成参考验收');
      await page.locator('#voice-reference-text').fill(reference.text);
      await page.locator('#voice-consent').check();
      await page.locator('#voice-file').setInputFiles(reference.path);
      await page.waitForFunction(() => !document.querySelector('#voice-create').disabled, null, { timeout: 30000 });
      await page.setViewportSize({ width: 1365, height: 1800 });
      await page.locator('#voice-clone-form').scrollIntoViewIfNeeded();
      await page.locator('#voice-clone-form').screenshot({ path: path.join(root, 'reports/voice-upload-ready.png') });
      await page.setViewportSize({ width: 1365, height: 1000 });
      const createResponse = responseFor('/api/voices');
      await page.locator('#voice-create').click();
      const created = await createResponse;
      assert.equal(created.status(), 200);
      const after = await created.json();
      const custom = after.voices.filter(v => !before.voices.some(old => old.id === v.id));
      assert.equal(custom.length, 1);
      createdVoiceId = custom[0].id;
      assert.equal(after.selected_id, before.selected_id, 'Uploading must not silently select the new voice');
      await page.locator('#voice-select').selectOption(createdVoiceId);
      assert.ok((await page.locator('#voice-message').textContent()).trim() || (await page.locator('#voice-description').textContent()).trim());
      const count = await page.evaluate(() => window.__voiceQA.audio.length);
      const previewResponse = responseFor('/api/voices/preview');
      await page.locator('#voice-preview').click();
      const preview = await previewResponse;
      assert.equal(preview.status(), 200);
      assert.equal(preview.headers()['x-voice-id'], createdVoiceId);
      await page.waitForFunction(n => window.__voiceQA.audio.slice(n).some(a => a.start), count, { timeout: 30000 });
      await page.locator('#voice-preview-stop').click();
      await page.waitForFunction(n => window.__voiceQA.audio.slice(n).some(a => a.stopped), count);
      report.custom_voice_id = createdVoiceId;
      return { custom_voice_id: createdVoiceId, synthetic_reference_only: true, preview_started_and_stopped: true,
        speaker_similarity: 'not_evaluated' };
    });
    await check('Adult deletes the test clone, restores the original voice and closes settings cleanly', async () => {
      const deletionResponse = responseFor(`/api/voices/${createdVoiceId}`, 'DELETE');
      await page.locator('#voice-delete').click();
      assert.equal((await deletionResponse).status(), 200);
      assert.equal((await api()).value.voices.some(v => v.id === createdVoiceId), false);
      createdVoiceId = null;
      await page.locator('#voice-select').selectOption(originalVoiceId);
      const saveResponse = responseFor('/api/voices/select');
      await page.locator('#voice-save').click();
      assert.equal((await saveResponse).status(), 200);
      assert.equal((await api()).value.selected_id, originalVoiceId);
      await page.locator('#parent-close').click();
      assert.equal(await allTracksEnded(), true);
      return { test_clone_deleted: true, original_voice_restored: true, all_tracks_ended: true };
    });
    await check('No JavaScript, console or CSP errors', async () => {
      assert.deepEqual(report.page_errors, []);
      assert.deepEqual(report.console_errors, []);
      assert.deepEqual(await page.evaluate(() => window.__voiceQA.csp), []);
    });
    report.passed = true;
  } catch (error) {
    report.passed = false;
    report.failure = error.message;
    process.exitCode = 1;
  } finally {
    if (page && !page.isClosed()) {
      try {
        report.observed = await page.evaluate(() => ({ audio: window.__voiceQA.audio, stops: window.__voiceQA.stops,
          csp: window.__voiceQA.csp, streams: window.__voiceQA.streams.map(s => s.getTracks().map(t => ({ state: t.readyState, enabled: t.enabled }))) }));
        // Cleanup only the synthetic voice created by this run. Adult authority
        // may have expired; report failure instead of altering another voice.
        if (createdVoiceId) report.cleanup_delete_status = await page.evaluate(async id => (await fetch(`/api/voices/${id}`, { method: 'DELETE' })).status, createdVoiceId);
        if (originalVoiceId && report.passed !== true) report.cleanup_restore_status = await page.evaluate(async id => (await fetch('/api/voices/select', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ voice_id: id }) })).status, originalVoiceId);
        await page.screenshot({ path: output.replace(/\.json$/, '.png'), fullPage: true });
      } catch (error) { report.cleanup_error = error.message; }
    }
    if (browser) await browser.close();
    fs.mkdirSync(path.dirname(output), { recursive: true });
    if (fs.existsSync(output)) {
      const history = path.join(root, 'reports/history'); fs.mkdirSync(history, { recursive: true });
      fs.copyFileSync(output, path.join(history, `${path.basename(output, '.json')}-${Date.now()}.json`));
    }
    fs.writeFileSync(output, JSON.stringify(report, null, 2) + '\n');
    console.log(JSON.stringify({ report: output, passed: report.passed, tests: report.tests.map(t => ({ name: t.name, passed: t.passed })), failure: report.failure }, null, 2));
  }
})();
